// ── Session builder — pick 20 random: 5+5+5+5 ────────────────────────────────
export function buildReadingSession(bank) {
  const pick = (arr, n) => shuffle([...arr]).slice(0, n);
  return [
    ...pick(bank.dua_suku   || bank.two_syllable,   5).map(w => ({ type:'speak', level:1, word: w })),
    ...pick(bank.tiga_suku  || bank.three_syllable,  5).map(w => ({ type:'speak', level:2, word: w })),
    ...pick(bank.empat_suku || bank.four_syllable,   5).map(w => ({ type:'speak', level:3, word: w })),
    ...pick(bank.ayat       || bank.sentences,       5).map(w => ({ type:'speak', level:4, word: w })),
  ];
}

function shuffle(arr) {
  for (let i = arr.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [arr[i], arr[j]] = [arr[j], arr[i]];
  }
  return arr;
}
